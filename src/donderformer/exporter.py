"""ChartExporter: package generated charts as song folders a TJA simulator can load.

Each source is a folder of ``<chart_id>.npz`` files as ``06_evaluation`` writes them to
``<run>/eval/ar_test/charts/`` (arrays ``generated``, ``clean`` and ``human``). Songs every source has
are exported side by side, one ``.tja`` per source next to a single copy of the audio::

    outputs/exports/<YYYYMMDD_HHMMSS>-<alias>/
    ├── export.json               # settings, sources, and where every chart came from
    └── Idol/
        ├── Idol.ogg
        ├── Idol (lstm).tja        # TITLE: Idol (lstm)
        ├── Idol (transformer).tja
        └── Idol (human).tja       # with include_human=True

Charts are written on each song's own BPM and OFFSET from the split manifest (see ``tja_export``).
"""
from __future__ import annotations

import json
import re
import shutil
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path

import numpy as np

from donderformer.data.data_splitter import read_manifest
from donderformer.data.tja import course_sections
from donderformer.data.tja_export import write_tja
from donderformer.paths import DataPaths, outputs_dir

NAME_PATTERN = re.compile(r"[A-Za-z0-9_.]+")
VERSION_KEYS = {"clean": "clean", "raw": "generated"}


def folder_name(title: str) -> str:
    """Song title made safe as a folder/file name on macOS, Linux and Windows."""
    return re.sub(r'[\\/:*?"<>|]+', "_", title).strip(" .") or "untitled"


@dataclass
class ChartExporter:
    alias: str                          # names the export folder, e.g. "lstm_vs_transformer"
    sources: dict[str, Path]            # label -> folder of <chart_id>.npz, e.g. {"lstm": run / "eval" / "ar_test" / "charts"}
    paths: DataPaths                    # data root holding the split manifest and the raw audio
    split: str                          # split the charts were generated from, e.g. "oni_v1"
    version: str = "clean"              # "clean" (back-to-back notes removed) or "raw"
    include_human: bool = False         # also write the human chart, from the first source's .npz
    songs: list[str] | None = None      # exact song titles to export; None = all
    n_songs: int | None = None          # only the first N songs (manifest order); ignored when songs is set
    frame_ms: int = 23
    rows: list[dict] = field(init=False, repr=False)

    def __post_init__(self):
        for name in (self.alias, *self.sources):
            if not NAME_PATTERN.fullmatch(name):
                raise ValueError(f"{name!r}: aliases and source labels may only use letters, digits, '_' and '.'")
        if not self.sources:
            raise ValueError("need at least one source")
        if self.include_human and "human" in self.sources:
            raise ValueError("'human' is reserved for include_human=True")
        if self.version not in VERSION_KEYS:
            raise ValueError(f"version must be one of {sorted(VERSION_KEYS)}")
        self.sources = {label: Path(folder) for label, folder in self.sources.items()}
        self.rows = self.select()

    def select(self) -> list[dict]:
        """Manifest rows every source has a .npz for, after the song filters."""
        rows = [row for row in read_manifest(self.paths, self.split)
                if all((folder / f"{row['chart_id']}.npz").exists() for folder in self.sources.values())]
        if self.songs is not None:
            unknown = sorted(set(self.songs) - {row["title"] for row in rows})
            if unknown:
                raise ValueError(f"Not generated by every source: {unknown}. "
                                 f"Available: {sorted(row['title'] for row in rows)}")
            rows = [row for row in rows if row["title"] in self.songs]
        elif self.n_songs is not None:
            rows = rows[:self.n_songs]
        return rows

    def level(self, row) -> int | None:
        """Star level from the manifest, else from the chart's own TJA (oni_v1 has blank level values)."""
        if row.get("level"):
            return int(float(row["level"]))
        text = (self.paths.raw / row["tja"]).read_text(encoding="utf-8-sig")
        levels = [s.level for s in course_sections(text) if s.course == row["course"]]
        return levels[0] if len(levels) == 1 else None

    def export(self) -> Path:
        """Write a new ``outputs/exports/<datetime>-<alias>/`` folder; returns its path."""
        out = outputs_dir() / "exports" / f"{datetime.now():%Y%m%d_%H%M%S}-{self.alias}"
        out.mkdir(parents=True, exist_ok=False)
        key = VERSION_KEYS[self.version]
        used, items = set(), []

        for row in self.rows:
            name = folder_name(row["title"])
            if name in used:                     # two charts with the same title
                name = f"{name} ({row['chart_id']})"
            used.add(name)
            song_dir = out / name
            song_dir.mkdir()
            audio = self.paths.raw / row["audio"]
            shutil.copy2(audio, song_dir / audio.name)

            charts = {}
            for label, folder in self.sources.items():
                with np.load(folder / f"{row['chart_id']}.npz") as data:
                    charts[label] = (data[key], folder)
            if self.include_human:
                folder = next(iter(self.sources.values()))
                with np.load(folder / f"{row['chart_id']}.npz") as data:
                    charts["human"] = (data["human"], folder)

            level = self.level(row)
            files = {}
            for label, (classes, folder) in charts.items():
                tja = song_dir / f"{name} ({label}).tja"
                write_tja(tja, classes, frame_ms=self.frame_ms, bpm=float(row["bpm"]),
                          offset=float(row["offset"]), title=f"{row['title']} ({label})",
                          wave=audio.name, course="Oni", level=level)
                files[label] = {"tja": tja.name, "from": str(folder / f"{row['chart_id']}.npz")}
            items.append({"title": row["title"], "chart_id": row["chart_id"], "folder": name, "charts": files})

        (out / "export.json").write_text(json.dumps({
            "alias": self.alias, "created": datetime.now().isoformat(timespec="seconds"),
            "split": self.split, "version": self.version, "include_human": self.include_human,
            "songs": self.songs, "n_songs": self.n_songs, "frame_ms": self.frame_ms,
            "sources": {label: str(folder) for label, folder in self.sources.items()},
            "items": items,
        }, indent=2, ensure_ascii=False), encoding="utf-8")
        print(f"Exported {len(items)} songs x {len(self.sources) + self.include_human} charts to {out}")
        return out
